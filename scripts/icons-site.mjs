// Builds one small icon stylesheet per public section from the full icons.css:
//   icons-site.css      → novels, home, categories, writers, pages (the busiest pages)
//   icons-shop.css      → bookstore
//   icons-account.css   → login / account
//   icons-community.css → community
// The full icons.css (every icon) stays for the admin panel and Seller Center.
// Each icon is an embedded SVG, so unused icons cost every visitor bytes and
// start-up time on slow phones. Runs automatically before each build.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const src = path.join(root, "src");
const full = fs.readFileSync(path.join(src, "styles/icons.css"), "utf8").replace(/^\/\*[\s\S]*?\*\/\n?/, "");

/** Files shared by every public section (layout shell, header, footer, nav, reader). */
const shared = ["components/HtmlShell.tsx", "components/Icons.tsx", "components/site", "components/reader", "components/useMe.ts", "styles/critical.css", "styles/style.css", "styles/mobile_nav.css"];
const sections = {
  site: ["app/(site)", "components/novel", "styles/single.css", "styles/index.css", "styles/drive-reader.css"],
  shop: ["app/(shop)", "components/shop", "styles/shop.css", "styles/single.css"],
  account: ["app/(account)", "components/account", "styles/account.css", "styles/account_app.css", "styles/auth.css"],
  community: ["app/(community)", "components/community", "styles/community.css"],
};

function collect(rel, used) {
  const p = path.join(src, rel);
  if (!fs.existsSync(p)) return;
  if (fs.statSync(p).isDirectory()) {
    for (const f of fs.readdirSync(p)) collect(path.join(rel, f), used);
    return;
  }
  if (!/\.(tsx?|jsx?|css)$/.test(p) || /icons(-\w+)?\.css$/.test(p)) return;
  for (const m of fs.readFileSync(p, "utf8").matchAll(/fa-[a-z0-9-]+/g)) used.add(m[0]);
}

const base = new Set();
shared.forEach((r) => collect(r, base));

for (const [name, dirs] of Object.entries(sections)) {
  const used = new Set(base);
  dirs.forEach((r) => collect(r, used));
  const out = [`/* AUTO-GENERATED by scripts/icons-site.mjs from icons.css — icons for the ${name} section only. Do not edit. */`];
  let kept = 0;
  for (const line of full.split("\n")) {
    const m = /^\.(fa-[a-z0-9-]+)\{--fa-svg/.exec(line);
    if (!m) out.push(line); // base rules, sizes, spin animation
    else if (used.has(m[1])) (out.push(line), kept++);
  }
  fs.writeFileSync(path.join(src, `styles/icons-${name}.css`), out.join("\n"));
  console.log(`icons-${name}.css: ${kept} icons`);
}
