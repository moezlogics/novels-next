// Builds src/styles/icons-site.css: only the icons the PUBLIC site uses.
// The full icons.css (every icon) stays for the admin panel and Seller Center.
// Every icon is an embedded SVG, and the page HTML carries the CSS, so unused icons
// cost every visitor bytes and start-up time on slow phones. Runs before each build.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const src = path.join(root, "src");
const full = fs.readFileSync(path.join(src, "styles/icons.css"), "utf8");

// public code only (admin + seller have their own full icon set)
const skip = [/[\\/]newlogin[\\/]/, /[\\/]seller[\\/]/, /[\\/]components[\\/]admin[\\/]/, /[\\/]components[\\/]seller[\\/]/, /settingsSchema\.ts$/];
const used = new Set();
(function walk(dir) {
  for (const f of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, f.name);
    if (f.isDirectory()) walk(p);
    else if (/\.(tsx?|jsx?|css)$/.test(f.name) && !/icons(-site)?\.css$/.test(f.name) && !skip.some((r) => r.test(p))) {
      for (const m of fs.readFileSync(p, "utf8").matchAll(/fa-[a-z0-9-]+/g)) used.add(m[0]);
    }
  }
})(src);

const out = ["/* AUTO-GENERATED by scripts/icons-site.mjs from icons.css — public-site icons only. Do not edit. */"];
let kept = 0;
let dropped = 0;
// drop the source file's own header comment
for (const line of full.replace(/^\/\*[\s\S]*?\*\/\n?/, "").split("\n")) {
  const m = /^\.(fa-[a-z0-9-]+)\{--fa-svg/.exec(line);
  if (!m) out.push(line); // base rules, sizes, spin animation, comments
  else if (used.has(m[1])) (out.push(line), kept++);
  else dropped++;
}
fs.writeFileSync(path.join(src, "styles/icons-site.css"), out.join("\n"));
console.log(`icons-site.css: ${kept} icons kept, ${dropped} unused dropped`);
