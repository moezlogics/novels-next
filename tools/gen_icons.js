#!/usr/bin/env node
/**
 * Generate css/icons.css — inline-SVG mask icons for every fa-* class used
 * on the public frontend. Replaces the FontAwesome webfont pipeline
 * (74KB CSS + 158KB woff2) with a few KB of instant, zero-CLS CSS.
 *
 * Usage:  node tools/gen_icons.js
 * Re-run whenever a new fa-* icon class is added to frontend PHP/JS.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', 'src');
const FA = path.join(__dirname, '..', 'node_modules', '@fortawesome', 'fontawesome-free');
const OUT = path.join(ROOT, 'styles', 'icons.css');

const EXCLUDE_DIRS = new Set(['node_modules', '.git', '.agents', '.claude', 'vendor', 'cache', 'tools']);
const EXTS = new Set(['.ts', '.tsx']);

// Non-icon fa-* utility classes to skip
const SKIP = new Set(['fa-solid', 'fa-regular', 'fa-brands', 'fa-light', 'fa-thin', 'fa-duotone',
  'fa-spin', 'fa-pulse', 'fa-fw', 'fa-xs', 'fa-sm', 'fa-lg', 'fa-xl', 'fa-2x', 'fa-stack',
  'fa-font-display', 'fa-v4compatibility', 'fa-beat', 'fa-fade', 'fa-flip', 'fa-shake', 'fa-bounce']);

function walk(dir, files = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.isDirectory()) {
      if (!EXCLUDE_DIRS.has(e.name)) walk(path.join(dir, e.name), files);
    } else if (EXTS.has(path.extname(e.name))) {
      files.push(path.join(dir, e.name));
    }
  }
  return files;
}

// 1. Collect used icon names + explicit fa-regular pairings
const used = new Set();
const regularPairs = new Set();
for (const f of walk(ROOT)) {
  const src = fs.readFileSync(f, 'utf8');
  for (const m of src.matchAll(/\bfa-[a-z0-9][a-z0-9-]*\b/g)) {
    if (!SKIP.has(m[0])) used.add(m[0].slice(3));
  }
  for (const m of src.matchAll(/fa-regular\s+fa-([a-z0-9-]+)/g)) {
    if (!SKIP.has('fa-' + m[1])) regularPairs.add(m[1]);
  }
}

// 2. Alias resolution from FA metadata (e.g. shopping-bag -> bag-shopping)
const meta = JSON.parse(fs.readFileSync(path.join(FA, 'metadata', 'icon-families.json'), 'utf8'));
const aliasMap = {};
for (const [name, def] of Object.entries(meta)) {
  for (const alias of (def.aliases && def.aliases.names) || []) aliasMap[alias] = name;
}

function svgFile(style, name) {
  const p = path.join(FA, 'svgs', style, name + '.svg');
  return fs.existsSync(p) ? p : null;
}

function findSvg(name) {
  const canonical = aliasMap[name] || name;
  for (const style of ['solid', 'brands', 'regular']) {
    const p = svgFile(style, canonical);
    if (p) return { style, path: p };
  }
  return null;
}

function toDataUri(file) {
  let svg = fs.readFileSync(file, 'utf8')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\s+/g, ' ')
    .trim();
  svg = svg
    .replace(/"/g, "'")
    .replace(/%/g, '%25')
    .replace(/#/g, '%23')
    .replace(/</g, '%3C')
    .replace(/>/g, '%3E')
    .replace(/&/g, '%26');
  return `url("data:image/svg+xml,${svg}")`;
}

// 3. Emit CSS
let css = `/* AUTO-GENERATED by tools/gen_icons.js — do not edit by hand.
 * Inline-SVG mask icons for all fa-* classes used on the public frontend.
 * Icons render instantly (no font download), inherit currentColor, zero CLS. */
i[class^="fa-"],i[class*=" fa-"],.fa,.fas,.far,.fab{display:inline-block;width:1.15em;height:1.15em;line-height:1;vertical-align:-.125em;flex-shrink:0;background-color:currentColor;-webkit-mask:var(--fa-svg,none) center/contain no-repeat;mask:var(--fa-svg,none) center/contain no-repeat}
.fa-fw{width:1.25em}.fa-xs{font-size:.75em}.fa-sm{font-size:.875em}.fa-lg{font-size:1.25em}.fa-xl{font-size:1.5em}.fa-2x{font-size:2em}
@keyframes fa-spin{to{transform:rotate(360deg)}}
.fa-spin{animation:fa-spin 2s linear infinite}
.fa-pulse{animation:fa-spin 1s steps(8) infinite}
`;

const missing = [];
const names = [...used].sort();
for (const name of names) {
  const hit = findSvg(name);
  if (!hit) { missing.push(name); continue; }
  css += `.fa-${name}{--fa-svg:${toDataUri(hit.path)}}\n`;
}
// Explicit regular-style variants (e.g. <i class="fa-regular fa-bookmark">)
for (const name of [...regularPairs].sort()) {
  const canonical = aliasMap[name] || name;
  const p = svgFile('regular', canonical);
  if (p) css += `.fa-regular.fa-${name}{--fa-svg:${toDataUri(p)}}\n`;
}

fs.writeFileSync(OUT, css);
const kb = (Buffer.byteLength(css) / 1024).toFixed(1);
console.log(`icons.css written: ${names.length - missing.length} icons, ${kb}KB`);
if (missing.length) console.warn('NOT FOUND (no SVG):', missing.join(', '));
